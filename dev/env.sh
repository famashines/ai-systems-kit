#!/bin/sh
set -eu
file="$(dirname "$0")/../.env.local"
[ -f "$file" ] && exit 0
umask 077
for name in ROOT ORCHESTRATION PROJECTIONS CONVERSATION_HUB AI_PROXY BUDGET AGENT_MANAGER PROMPT_STUDIO NOTIFICATION AUDIT_TRACE \
  AI_SYSTEMS_ADMIN AI_SYSTEMS_ORCHESTRATION AI_SYSTEMS_PROJECTIONS AI_SYSTEMS_CONVERSATION_HUB AI_SYSTEMS_AI_PROXY \
  AI_SYSTEMS_BUDGET AI_SYSTEMS_AGENT_MANAGER AI_SYSTEMS_PROMPT_STUDIO AI_SYSTEMS_NOTIFICATION AI_SYSTEMS_AUDIT_TRACE \
  AI_SYSTEMS_SOCKET_GATEWAY; do
  printf '%s_PASSWORD=%s\n' "$name" "$(od -An -N24 -tx1 /dev/urandom | tr -d ' \n')"
done > "$file"
echo "wrote $file"
